document.addEventListener("DOMContentLoaded", () => {
    const langSelect = document.getElementById("lang-select");
    langSelect.addEventListener("change", (e) => {
        setLanguage(e.target.value);
    });
    
    const userLang = navigator.language || navigator.userLanguage;
    let defaultLang = 'es';
    if (userLang.startsWith('en')) defaultLang = 'en';
    if (userLang.startsWith('fr')) defaultLang = 'fr';
    if (userLang.startsWith('ru')) defaultLang = 'ru';
    
    langSelect.value = defaultLang;
    setLanguage(defaultLang);
});

function setLanguage(lang) {
    document.documentElement.lang = lang;
    const t = translations[lang];
    if (!t) return;
    
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (t[key]) {
            el.innerHTML = t[key];
        }
    });
    
    const metas = {
        'description': t.site_desc,
        'og:title': t.site_title,
        'og:description': t.site_desc,
        'twitter:title': t.site_title,
        'twitter:description': t.site_desc
    };
    
    document.title = t.site_title;
    for (const [name, content] of Object.entries(metas)) {
        let metaEl = document.querySelector(`meta[name="${name}"]`) || document.querySelector(`meta[property="${name}"]`);
        if (metaEl) {
            metaEl.content = content;
        }
    }
}
